
public class _3_for {
    public static void main(String[] args) {
        // Definition: A for loop is a control flow statement that allows code to be executed repeatedly for a specified number of iterations. It consists of three main components: initialization, condition, and update.
        // Syntax:
        // for (initialization; condition; update) {
        //     // code to be executed repeatedly
        // }
        // Here, the initialization is executed once at the beginning of the loop. The condition is evaluated before each iteration, and if it is true, the code block inside the for loop is executed. After each iteration, the update statement is executed. This process repeats until the condition evaluates to false.

        // Example of a for loop
        // Print numbers from 1 to 5

        for (int number = 1; number <= 5; number++) {
            System.out.println(number);
        }
    }
}
