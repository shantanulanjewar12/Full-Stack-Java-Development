
public class _1_simple_if_statement {
    public static void main(String[] args) {

        // Definition: A simple if statement is a control flow statement that allows you to execute a block of code only if a specified condition evaluates to true.
        // Syntax:
        // if (condition) {
        //     // code to be executed if condition is true
        // }
        // Here, the condition is evaluated, and if it is true, the code block inside the if statement is executed. If the condition is false, the code block is skipped.
    

        // Example of a simple if statement
        // Check if a person is eligible to vote
        // Assuming the voting age is 18
        
        int age = 20;
        if (age >= 18) {
            System.out.println("You are eligible to vote.");
        }

    }
}
